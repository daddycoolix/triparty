def _in(poly, la, ln):
    n = len(poly); c = False
    for i in range(n):
        a1, o1 = poly[i]; a2, o2 = poly[(i + 1) % n]
        if (o1 > ln) != (o2 > ln) and la < (a2 - a1) * (ln - o1) / (o2 - o1) + a1: c = not c
    return c


def inside(la, ln):
    return 41.317 < la < 41.470 and 2.052 < ln < 2.230


def district(la, ln):
    if not inside(la, ln): return X
    for d in (G, B, R, P):
        if _in(POLY[d], la, ln): return d
    diag = 41.3925 + 0.352 * (ln - 2.1440)          # קו הדיאגונל, משוער
    if la < 41.3775 and ln < 2.1780 and la > 41.345: return M        # מונז'ואיק, פובלה סק
    if ln < 2.1420 and la < 41.3795 and la > 41.355: return M        # סנטס
    if la >= 41.4030 and 2.1380 <= ln < 2.1700 and la < 41.4280: return GR
    if la > diag and 2.1500 <= ln < 2.1630 and la < 41.4030: return GR
    if ln >= 2.1858 and 41.3835 <= la <= 41.4200 and (la >= 41.4005 or ln >= 2.1885) and (la <= 41.4120 or ln > 2.1920): return S
    if 41.3745 <= la < 41.4145 and 2.1420 <= ln < 2.1890 and (la <= diag or ln >= 2.1630): return E
    if ln < 2.1500 and la >= 41.3795 and la < 41.4350: return T
    return O


def center(la, ln):
    return district(la, ln) in CENTER


